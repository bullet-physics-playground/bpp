PovScriptWriter::PovScriptWriter() {
  // Default lights
  PovLight sun;
  sun.type = PovLight::Directional;
  sun.direction = btVector3(0.5, -1, 0.3);
  sun.color = "rgb <1, 0.95, 0.9>";
  sun.intensity = 1.0;
  m_lights.append(sun);

  PovLight fill;
  fill.type = PovLight::Point;
  fill.position = btVector3(-5, 5, -5);
  fill.color = "rgb <0.3, 0.4, 0.6>";
  fill.intensity = 0.3;
  m_lights.append(fill);
}

void PovScriptWriter::addObject(Object *obj, const QString & /*sceneDir*/) {
  if (!obj) return;
  m_objects.append(obj);
}

bool PovScriptWriter::writeScene(const QString &sceneDir, int frame) {
  QDir dir(sceneDir);
  if (!dir.exists()) {
    if (!dir.mkpath(".")) {
      qWarning() << "Failed to create scene directory:" << sceneDir;
      return false;
    }
  }

  writeMeshIncludes(sceneDir);
  return writeMainFile(sceneDir, frame);
}

bool PovScriptWriter::writeMainFile(const QString &sceneDir, int frame) {
  QString mainFile = sceneDir + "/scene.pov";
  QFile file(mainFile);
  if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
    qWarning() << "Failed to open main scene file:" << mainFile;
    return false;
  }

  QTextStream s(&file);
  s.setCodec("UTF-8");

  writeHeader(s, frame);
  writeGlobalSettings(s);
  writeCamera(s);
  writeLights(s);
  writeBackground(s);
  writeObjects(s, sceneDir, frame);

  file.close();
  return true;
}

void PovScriptWriter::writeMeshIncludes(const QString &sceneDir) {
  QDir dir(sceneDir);
  if (!dir.exists()) dir.mkpath(".");

  // Write each unique mesh to its own include file
  QHash<QString, QVector<Object *>> meshesByHash;
  for (Object *obj : m_objects) {
    QString hash = generateMeshHash(obj);
    if (!hash.isEmpty()) {
      m_objectHashes[obj] = hash;
      meshesByHash[hash].append(obj);
    }
  }

  for (auto it = meshesByHash.begin(); it != meshesByHash.end(); ++it) {
    const QString &hash = it.key();
    const QVector<Object *> &objects = it.value();

    if (objects.isEmpty()) continue;

    // Use first object to generate mesh
    Object *obj = objects.first();
    QString filename = getSharedMeshFile(hash);
    QString filepath = sceneDir + "/" + filename;

    QFile file(filepath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
      qWarning() << "Failed to open mesh include:" << filepath;
      continue;
    }

    QTextStream s(&file);
    obj->toMesh2(&s, hash);
    file.close();

    m_sharedMeshes[hash] = filename;
  }
}

QString PovScriptWriter::generateMeshHash(Object *obj) const {
  if (!obj || !obj->getCollisionShape()) return QString();

  // Use object's built-in mesh hash if available
  // Otherwise create a simple hash from object properties
  QByteArray data;
  data.append(obj->toString().toUtf8());
  data.append(QString::number(obj->getPosition().x()).toUtf8());
  data.append(QString::number(obj->getPosition().y()).toUtf8());
  data.append(QString::number(obj->getPosition().z()).toUtf8());

  // Add shape-specific data
  if (obj->getCollisionShape()) {
    btVector3 aabbMin, aabbMax;
    obj->getCollisionShape()->getAabb(obj->getTransform(), aabbMin, aabbMax);
    data.append(QString::number(aabbMin.x()).toUtf8());
    data.append(QString::number(aabbMin.y()).toUtf8());
    data.append(QString::number(aabbMin.z()).toUtf8());
    data.append(QString::number(aabbMax.x()).toUtf8());
    data.append(QString::number(aabbMax.y()).toUtf8());
    data.append(QString::number(aabbMax.z()).toUtf8());
  }

  QByteArray hash = QCryptographicHash::hash(data, QCryptographicHash::Md5);
  return QString(hash.toHex().left(16));
}

void PovScriptWriter::registerSharedMesh(Object *obj, const QString &hash) {
  m_sharedMeshes[hash] = "mesh_" + hash + ".inc";
  m_objectHashes[obj] = hash;
}

bool PovScriptWriter::isSharedMesh(const QString &hash) const {
  return m_sharedMeshes.contains(hash);
}

QString PovScriptWriter::getSharedMeshFile(const QString &hash) const {
  return m_sharedMeshes.value(hash, "mesh_" + hash + ".inc");
}

void PovScriptWriter::writeHeader(QTextStream &s, int frame) {
  s << "// POV-Ray scene generated by BPP (Moray-style exporter)\n";
  s << "// Generated: " << QDateTime::currentDateTime().toString(Qt::ISODate) << "\n";
  s << "// Frame: " << frame << "\n\n";

  s << "#version " << m_settings.version << ";\n\n";

  if (!m_settings.globalSettings.isEmpty()) {
    s << "// Global settings\n";
    for (const QString &gs : m_settings.globalSettings) {
      s << gs << "\n";
    }
    s << "\n";
  }

  s << "global_settings {\n";
  s << "  assumed_gamma " << m_settings.assumedGamma << "\n";
  s << "  max_trace_level " << m_settings.maxTraceLevel << "\n";
  s << "  adc_bailout 0.001\n";

  if (m_settings.radiosityEnabled) {
    s << "  radiosity {\n";
    s << "    count            " << m_settings.radCount << "\n";
    s << "    error_bound      " << m_settings.radErrorBound << "\n";
    s << "    gray_threshold   " << m_settings.radGrayThreshold << "\n";
    s << "    low_error_factor " << m_settings.radLowErrorFactor << "\n";
    s << "    minimum_reuse    " << m_settings.radMinimumReuse << "\n";
    s << "    nearest_count    " << m_settings.radNearestCount << "\n";
    s << "    recursion_limit  " << m_settings.radRecursionLimit << "\n";
    s << "    adc_bailout      " << m_settings.radADCBailout << "\n";
    s << "    max_sample       " << m_settings.radMaximumSample << "\n";
    s << "    media            " << (m_settings.radMedia ? "on" : "off") << "\n";
    s << "    normal           " << (m_settings.radNormal ? "on" : "off") << "\n";
    s << "    always_sample    " << (m_settings.radAlwaysSample ? "1" : "0") << "\n";
    s << "    pretrace_start   " << m_settings.radPreTraceStart << "\n";
    s << "    pretrace_end     " << m_settings.radPreTraceEnd << "\n";
    s << "  }\n";
  }

  if (m_settings.photonsEnabled) {
    s << "  photons {\n";
    if (m_settings.photonUseSpacing) {
      s << "    spacing          " << m_settings.photonSpacing << "\n";
    } else {
      s << "    count            " << m_settings.photonCount << "\n";
    }
    s << "    gather           " << m_settings.photonGatherMin << ", "
      << m_settings.photonGatherMax << "\n";
    if (m_settings.photonMedia) {
      s << "    media            " << m_settings.photonMediaMaxSteps << ", "
        << m_settings.photonMediaFactor << "\n";
    }
    s << "    jitter           " << m_settings.photonJitter << "\n";
    s << "    max_trace_level  " << m_settings.photonMaxTraceLevel << "\n";
    s << "    autostop         " << m_settings.photonAutoStop << "\n";
    if (m_settings.photonUseRadiusOverride || m_settings.photonUseRadiusFactor) {
      s << "    radius           ";
      if (m_settings.photonUseRadiusOverride)
        s << m_settings.photonRadius;
      s << ", ";
      if (m_settings.photonUseRadiusFactor)
        s << m_settings.photonRadiusFactor;
      s << "\n";
    }
    s << "    expand_thresholds " << m_settings.photonExpandThresholds << ", "
      << m_settings.photonExpandMin << "\n";
    s << "  }\n";
  }

  s << "}\n\n";

  if (m_settings.fogEnabled) {
    s << "// Fog\n";
    s << "fog {\n";
    s << "  fog_type " << m_settings.fogType << "\n";
    s << "  distance     " << m_settings.fogDistance << "\n";
    s << "  color " << m_settings.fogColor << "\n";
    if (m_settings.fogFilter != 0.0 || m_settings.fogTrans != 0.0) {
      s << "  filter " << m_settings.fogFilter << "\n";
      s << "  transmit " << m_settings.fogTrans << "\n";
    }
    if (!m_settings.fogTurbulence.isEmpty()) {
      s << "  turbulence " << m_settings.fogTurbulence << "\n";
      s << "  omega      " << m_settings.fogOmega << "\n";
      s << "  lambda     " << m_settings.fogLambda << "\n";
      s << "  octaves    " << m_settings.fogOctaves << "\n";
      s << "  turb_depth " << m_settings.fogTurbDepth << "\n";
    }
    if (m_settings.fogGround) {
      s << "  up           <0,0,1>\n";
      s << "  fog_offset   " << m_settings.fogOffset << "\n";
      s << "  fog_alt      " << m_settings.fogAltitude << "\n";
    }
    s << "}\n\n";
  }

  if (m_settings.atmosphereEnabled) {
    s << "// Atmosphere\n";
    if (m_settings.atmosphereMedia && !m_settings.atmosphereMediaName.isEmpty()) {
      s << "media { " << m_settings.atmosphereMediaName << " }\n\n";
    }
  }
}

void PovScriptWriter::writeGlobalSettings(QTextStream & /*s*/) {
  // Already written in header
}

void PovScriptWriter::writeCamera(QTextStream &s) {
  s << "// Camera\n";
  s << "camera {\n";

  if (m_settings.cameraType == "orthographic") {
    s << "  orthographic\n";
  } else if (m_settings.cameraType == "fisheye") {
    s << "  fisheye\n";
  } else if (m_settings.cameraType == "ultra_wide_angle") {
    s << "  ultra_wide_angle\n";
  } else if (m_settings.cameraType == "spherical") {
    s << "  spherical\n";
  } else if (m_settings.cameraType == "cylindrical") {
    s << "  cylindrical\n";
  }

  s << "  location <" << m_settings.cameraLocation.x() << ", "
    << m_settings.cameraLocation.y() << ", " << m_settings.cameraLocation.z() << ">\n";
  s << "  look_at <" << m_settings.cameraLookAt.x() << ", "
    << m_settings.cameraLookAt.y() << ", " << m_settings.cameraLookAt.z() << ">\n";

  if (m_settings.cameraType != "orthographic" && m_settings.cameraType != "spherical") {
    s << "  sky <" << m_settings.cameraSky.x() << ", "
      << m_settings.cameraSky.y() << ", " << m_settings.cameraSky.z() << ">\n";
    s << "  angle " << m_settings.cameraAngle << "\n";
  }

  if (m_settings.cameraType == "orthographic") {
    s << "  right x*image_width/image_height\n";
  }

  s << "}\n\n";
}

void PovScriptWriter::writeLights(QTextStream &s) {
  s << "// Lights\n";
  for (const PovLight &light : m_lights) {
    if (light.type == PovLight::Point || light.type == PovLight::Spot) {
      s << "light_source {\n";
      s << "  <" << light.position.x() << ", " << light.position.y() << ", " << light.position.z() << ">\n";
      s << "  color " << light.color << " * " << light.intensity << "\n";

      if (light.type == PovLight::Spot) {
        s << "  spotlight\n";
        s << "  direction <" << light.direction.x() << ", " << light.direction.y() << ", " << light.direction.z() << ">\n";
        s << "  point_at <" << (light.position.x() + light.direction.x()) << ", "
          << (light.position.y() + light.direction.y()) << ", " << (light.position.z() + light.direction.z()) << ">\n";
        if (light.falloff > 0) s << "  falloff " << light.falloff << "\n";
        if (light.tightness > 0) s << "  tightness " << light.tightness << "\n";
        if (light.radius > 0) s << "  radius " << light.radius << "\n";
      }

      if (!light.shadows) s << "  shadowless\n";

      for (const QString &m : light.media) {
        s << "  " << m << "\n";
      }

      s << "}\n\n";
    } else if (light.type == PovLight::Directional) {
      s << "light_source {\n";
      s << "  <" << light.direction.x() << ", " << light.direction.y() << ", " << light.direction.z() << ">\n";
      s << "  color " << light.color << " * " << light.intensity << "\n";
      s << "  parallel\n";
      if (!light.shadows) s << "  shadowless\n";
      s << "}\n\n";
    } else if (light.type == PovLight::Area) {
      s << "light_source {\n";
      s << "  <" << light.position.x() << ", " << light.position.y() << ", " << light.position.z() << ">\n";
      s << "  color " << light.color << " * " << light.intensity << "\n";
      s << "  area_light <1, 0, 0>, <0, 0, 1>, 10, 10\n";
      s << "  adaptive 1\n";
      s << "  jitter\n";
      if (!light.shadows) s << "  shadowless\n";
      s << "}\n\n";
    }
  }
}

void PovScriptWriter::writeBackground(QTextStream &s) {
  s << "// Background\n";
  s << "background { color " << m_settings.backgroundColor << " }\n\n";
}

void PovScriptWriter::writeObjects(QTextStream &s, const QString & /*sceneDir*/, int frame) {
  s << "// Objects\n";

  for (Object *obj : m_objects) {
    if (!obj->getPOVExport()) continue;

    QString hash = m_objectHashes.value(obj);
    if (!hash.isEmpty() && isSharedMesh(hash)) {
      // Use shared mesh include
      QString meshFile = getSharedMeshFile(hash);
      s << "#include \"" << meshFile << "\"\n";
      s << "object { " << sanitizeFilename(hash) << "\n";
    } else {
      // Inline object
      obj->toPOV(&s);
    }

    if (m_settings.isAnimation) {
      // Add clock-based transformations if needed
      s << "  // frame " << frame << "\n";
    }

    s << "}\n\n";
  }
}

QString PovScriptWriter::sanitizeFilename(const QString &name) const {
  QString result = name;
  result.replace(QRegularExpression("[^a-zA-Z0-9_]"), "_");
  return result;
}

bool exportPovScene(const QVector<Object *> &objects,
                    const QString &sceneDir,
                    const PovSceneSettings &settings,
                    int frame) {
  PovScriptWriter writer;
  writer.setSceneSettings(settings);

  for (Object *obj : objects) {
    writer.addObject(obj, sceneDir);
  }

  return writer.writeScene(sceneDir, frame);
}