-- Build one solid as a btTriangleMesh rigid body, exactly like
-- demo/basic/08-trimesh.lua. Faces are triangulated by a fan from the
-- first vertex.
local function build(name, params)
  params = params or {}
  options = {
    size = 1,
    mass = 0.1,
    col  = "#103070",
  }
  for k, v in pairs(params) do options[k] = v end

  data = solids[name]

  m = btTriangleMesh()
  pts = {}
  for i = 1, #data.points do
    p = data.points[i]
    pts[i] = btVector3(p[1] * options.size, p[2] * options.size,
                       p[3] * options.size)
  end

  -- face normal by Newell's method
  local function newell(face)
    local nx, ny, nz = 0, 0, 0
    for i = 1, #face do
      local a = pts[face[i] + 1]
      local b = pts[face[(i % #face) + 1] + 1]
      nx = nx + (a.y - b.y) * (a.z + b.z)
      ny = ny + (a.z - b.z) * (a.x + b.x)
      nz = nz + (a.x - b.x) * (a.y + b.y)
    end
    return btVector3(nx, ny, nz)
  end

  -- fan-triangulate each face, flipping any triangle whose winding opposes
  -- the face normal (star faces such as pentagrams and great decagons)
  for _, face in ipairs(data.faces) do
    local n = newell(face)
    for i = 2, #face - 1 do
      local a = pts[face[1] + 1]
      local b = pts[face[i] + 1]
      local c = pts[face[i + 1] + 1]
      if (b - a):cross(c - a):dot(n) < 0 then
        m:addTriangle(a, c, b, true)
      else
        m:addTriangle(a, b, c, true)
      end
    end
  end

  qtn = btQuaternion()
  trans = btTransform()
  trans:setIdentity()
  qtn:setEuler(0.0, 0.0, 0.0)
  trans:setRotation(qtn)
  trans:setOrigin(btVector3(0, 0, 0))

  ms = btDefaultMotionState(trans)

  shape = btGImpactMeshShape(m)
  shape:updateBound()

  inertia = btVector3()
  shape:calculateLocalInertia(options.mass, inertia)
  body = btRigidBody(options.mass, ms, shape, inertia)

  obj = Mesh()
  obj.col      = options.col
  obj.shape    = shape
  obj.body     = body
  obj.mesh     = m
  obj.mass     = options.mass
  obj.inertia  = 20.9
  obj.damp_lin = 0.0
  obj.damp_ang = 0.0

  return obj
end

local function make(name)
  return function(params)
    return build(name, params)
  end
end

