#!/bin/sh
# make-pdfs.sh -- typeset every .md file in the hall as a .pdf beside it.
# Run it whenever a .md file changes (needs: pip install markdown playwright).
set -e
cd "$(dirname "$0")"
pdf() { python3 tools/md2pdf.py "$@"; }
pdf README.md                          --sub "A Victorian hall of machines that compute"
pdf MACHINES.md                        --sub "Every machine considered, in the order the hall walks them"
pdf HANDOFF.md                         --sub "For a new chat: how to work, build, test, and what's next"
pdf exhibits/Suanpan/README.md         --sub "West bay 1: the Chinese abacus"
pdf exhibits/Suanpan/FINDINGS.md       --sub "West bay 1: the suanpan"
pdf exhibits/Suanpan/MANUAL.md         --sub "West bay 1: how to work a Chinese abacus"
pdf exhibits/SlideRule/README.md       --sub "East bay 1: multiplying by adding lengths"
pdf exhibits/SlideRule/MANUAL.md       --sub "East bay 1: how to work a slide rule"
pdf exhibits/SlideRule/FINDINGS.md     --sub "East bay 1: the slide rule"
pdf exhibits/NapiersBones/README.md    --sub "West bay 2: the multiplication table, cut into rods"
pdf exhibits/NapiersBones/FINDINGS.md  --sub "West bay 2: Napier's bones"
pdf exhibits/DominoAdder/README.md     --sub "West bay 3: dominoes that add two bits"
pdf exhibits/DominoAdder/FINDINGS.md   --sub "West bay 3: the Domino Half Adder"
pdf exhibits/Differential/README.md    --sub "East bay 3: bevel gears that add and subtract"
pdf exhibits/Differential/FINDINGS.md  --sub "East bay 3: the Differential"
pdf exhibits/Pascaline/README.md       --sub "West bay 4: Pascal's adding machine (1642)"
pdf exhibits/Pascaline/FINDINGS.md     --sub "West bay 4: the Pascaline"
pdf exhibits/LehmerSieve/README.md     --sub "West bay 6: wheels that sieve for factors"
pdf exhibits/LehmerSieve/FINDINGS.md   --sub "West bay 6: Lehmer's number sieve"
pdf exhibits/DigiComp2/README.md       --sub "East bay 6: balls that compute in binary"
pdf exhibits/DigiComp2/FINDINGS.md     --sub "East bay 6: the Digi-Comp II"
pdf exhibits/DigiComp2/MANUAL.md       --sub "East bay 6: how the Digi-Comp II computes, operation by operation"
pdf exhibits/GaltonBoard/README.md     --sub "West bay 5: balls that fall into the normal curve"
pdf exhibits/GaltonBoard/FINDINGS.md   --sub "West bay 5: the Galton board"
pdf exhibits/GaltonBoard/SPLITTERS.md  --sub "East bay 5: the splitter board and its splitters"
